"""平台能力映射；extra 只保留内容元信息，不转储账号或网络响应"""
import asyncio
from desktop.content.schema import group, number
from desktop.content.subtitles import load
from desktop.links import media_referer
from desktop.media_download import secure_url


def urls(value):
    if isinstance(value, dict):
        value = value.get('url_list', value.get('urlList', []))
    if isinstance(value, str):
        value = [value]
    return list(dict.fromkeys(secure_url(u) for u in (value or []) if isinstance(u, str) and u.startswith(('https://', 'http://', '//'))))


def pick(data, *keys):
    return {k: data[k] for k in keys if k in data}


def images(platform, raw, record):
    items = []
    if platform == 'dy':
        video = raw.get('video') or {}
        for role in ('cover', 'origin_cover', 'cover_original_scale', 'dynamic_cover'):
            image = video.get(role) or {}
            for url in urls(image):
                items.append({'role': role, 'url': url, 'width': image.get('width'), 'height': image.get('height')})
        for i, image in enumerate(raw.get('images') or []):
            for url in urls(image):
                items.append({'role': 'image', 'index': i, 'url': url, 'width': image.get('width'), 'height': image.get('height')})
    elif platform == 'xhs':
        for i, image in enumerate(raw.get('image_list') or raw.get('imageList') or []):
            for info in image.get('info_list') or image.get('infoList') or []:
                for url in urls(info.get('url')):
                    items.append({'index': i, 'role': info.get('image_scene', info.get('imageScene')),
                                  'url': url, 'width': image.get('width'), 'height': image.get('height'),
                                  'livePhoto': image.get('live_photo', image.get('livePhoto'))})
            for role in ('url_default', 'urlDefault', 'url_pre', 'urlPre'):
                for url in urls(image.get(role)):
                    items.append({'index': i, 'role': role, 'url': url, 'width': image.get('width'), 'height': image.get('height'),
                                  'livePhoto': image.get('live_photo', image.get('livePhoto'))})
    if not items:
        items = [{'role': 'image', 'url': u, 'width': None, 'height': None} for u in record.get('images', [])]
    record['imageVariants'] = group(items)


def douyin(raw, record):
    music = raw.get('music') or {}
    audio = urls(music.get('play_url'))
    record['audioResources'] = group([{'role': 'original_sound' if music.get('is_original_sound') else 'music',
        'url': audio[0], 'backupUrls': audio[1:], 'title': music.get('title'), 'durationSeconds': music.get('duration'),
        'matchesFullVideoAudio': None}] if audio else [])
    record['storyboards'] = group([{'urls': urls(b.get('img_urls') or b.get('img_url')),
        'frameCount': b.get('img_num'), 'intervalSeconds': b.get('interval'),
        'columns': b.get('img_x_len'), 'rows': b.get('img_y_len'),
        'frameWidth': b.get('img_x_size'), 'frameHeight': b.get('img_y_size')}
        for b in (raw.get('video') or {}).get('big_thumbs') or []])
    record['chapters'] = group([{'title': c.get('desc'), 'description': c.get('detail'),
        'start': number(c.get('timestamp')) / 1000 if number(c.get('timestamp')) is not None else None,
        'end': None, 'imageUrl': next(iter(urls(c.get('url'))), None)} for c in raw.get('chapter_list') or []])
    mix = raw.get('mix_info') or {}
    record['collections'] = group([pick(mix, 'mix_id', 'mix_name', 'desc', 'total')] if mix else [])
    record['extra']['dy'] = {'music': pick(music, 'title', 'is_original', 'is_original_sound', 'duration'),
        'video': pick(raw.get('video') or {}, 'has_watermark', 'is_source_HDR', 'cdn_url_expired', 'ratio'),
        'tags': [pick(t, 'tag_id', 'tag_name', 'level') for t in raw.get('video_tag') or []],
        'downloadPolicy': pick(raw.get('video_control') or {}, 'allow_download', 'allow_share', 'prevent_download')}
    tracks = []
    video = raw.get('video') or {}
    captions = list((video.get('cla_info') or {}).get('caption_infos') or [])
    captions += video.get('subtitle_infos') or video.get('subtitleInfos') or []
    for s in captions:
        u = urls(s.get('url') or s.get('Url'))
        if u:
            tracks.append({'url': u[0], 'language': s.get('lang') or s.get('LanguageCodeName'),
                           'label': s.get('language_name'), 'source': 'platform', 'isAutoGenerated': None})
    for sticker in raw.get('interaction_stickers') or []:
        for s in (sticker.get('auto_video_caption_info') or {}).get('auto_captions') or []:
            u = urls(s.get('url'))
            if u:
                tracks.append({'url': u[0], 'language': s.get('language'), 'label': None,
                               'source': 'platform', 'isAutoGenerated': True})
    return tracks


async def bilibili(runner, raw, record):
    view = raw.get('_view') or {}
    record['parts'] = group([{'id': str(p.get('cid')), 'index': p.get('page'), 'title': p.get('part'),
        'durationSeconds': p.get('duration'), 'dimensions': p.get('dimension')} for p in view.get('pages') or []])
    collection = view.get('ugc_season') or {}
    record['collections'] = group([pick(collection, 'id', 'title', 'intro', 'ep_count', 'season_type')] if collection else [])
    record['extra']['bili'] = {'formats': [pick(f, 'quality', 'format', 'new_description', 'display_desc', 'superscript', 'codecs', 'need_login', 'need_vip') for f in raw.get('support_formats') or []],
        'acceptedQualities': raw.get('accept_quality') or [], 'qualityLabels': raw.get('accept_description') or [],
        'rights': pick(view.get('rights') or {}, 'is_stein_gate', 'is_cooperation', 'is_360', 'is_4k'),
        'selectedPartId': raw.get('_cid')}
    try:
        async with asyncio.timeout(15):
            player = await runner.client.get('/x/player/wbi/v2', {'aid': view.get('aid') or int(record['id'].split(':')[-1]),
                                                                'cid': raw['_cid']}, enable_params_sign=False)
        record['chapters'] = group([{'title': c.get('content'), 'start': c.get('from'), 'end': c.get('to'),
            'imageUrl': next(iter(urls(c.get('imgUrl'))), None)} for c in player.get('view_points') or []])
        if player.get('need_login_subtitle'):
            record['subtitles'] = group(status='login_required')
            return
        tracks = []
        for s in (player.get('subtitle') or {}).get('subtitles') or []:
            u = urls(s.get('subtitle_url'))
            if u:
                tracks.append({'id': str(s.get('id')), 'language': s.get('lan'), 'label': s.get('lan_doc'),
                    'isAutoGenerated': True if str(s.get('lan', '')).startswith('ai-') else None, 'source': 'platform',
                    'platformAiType': s.get('ai_type'), 'url': u[0]})
        record['subtitles'] = await load(tracks, media_referer('bili'))
    except Exception as error:
        record['subtitles'] = group(status='failed', error='timeout' if isinstance(error, TimeoutError) else 'player_request_failed')
        if record['chapters']['status'] == 'not_requested':
            record['chapters'] = group(status='failed', error='player_request_failed')


async def enrich(runner, raw, record):
    platform = runner.platform
    images(platform, raw, record)
    audios = [{**v, 'role': 'video_audio', 'matchesFullVideoAudio': True}
              for v in record['media']['variants'] if v['kind'] == 'audio']
    record['audioResources'] = group(audios)
    if platform == 'bili':
        await bilibili(runner, raw, record)
    elif platform == 'dy':
        tracks = douyin(raw, record)
        record['subtitles'] = await load(tracks, media_referer(platform))
    elif platform == 'xhs':
        video = raw.get('video') or {}
        record['extra']['xhs'] = {'tags': [pick(t, 'id', 'name', 'type') for t in raw.get('tag_list') or raw.get('tagList') or []],
            'videoMetadata': pick((video.get('media') or {}).get('video') or {}, 'duration', 'hdr_type', 'hdrType', 'drm_type', 'drmType'),
            'updatedAtSource': raw.get('last_update_time', raw.get('lastUpdateTime'))}
        # 尚无可靠字幕/章节接口，不能把未实现写成平台没提供
    else:
        record['extra'].setdefault(platform, {})
